import fs from "fs";
import path from "path";
import { execFile } from "child_process";
import { promisify } from "util";
import { logError, logWarn } from "../LogService";
import { IError } from "../structures/Interfaces";

const execFileAsync = promisify(execFile);

// Default server-block template used to seed a project's <name>.server.conf on first deploy.
// Devops owns this file after seed — deployer NEVER overwrites it again, so it's safe for
// certbot to inject SSL directives and for operator to add locations, headers, etc.
//
// Uses `_{{DOMAIN}}_` and `_{{UPSTREAM}}_` markers; deployer substitutes them once at seed time.
// SSL is intentionally NOT here — devops runs `certbot --nginx -d _{{DOMAIN}}_` which appends
// `listen 443 ssl; ssl_certificate ...;` into this same file. Deployer stays out of the way.
export const DEFAULT_SERVER_TEMPLATE = `# Seeded by deployer for _{{DOMAIN}}_. SAFE TO EDIT.
# Deployer NEVER overwrites this file after the initial seed.
# Add SSL by running:  certbot --nginx -d _{{DOMAIN}}_

server {
    server_name _{{DOMAIN}}_;
    listen 80;

    location / {
        proxy_pass http://_{{UPSTREAM}}_;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        # WebSocket: pass the upgrade handshake through to the app.
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_read_timeout 60s;
    }
}
`;

// Two-file per-project design:
//   <name>.upstream.conf — TINY, deployer owns fully, overwritten on every activate
//   <name>.server.conf   — LARGE, deployer seeds once, devops owns forever after
// Deployer only touches the port (via upstream name → server mapping). Devops edits the
// server block freely (SSL from certbot, extra locations, CORS, whatever). Ownership never
// overlaps → no marker parsing, no in-place surgery, no risk of clobbering devops edits.
export class NginxHelper {

    // Overwrites (atomically) the upstream config file with the current active port.
    // Called by deployer on every activate — this is the only nginx file deployer owns fully.
    // Content is minimal: single `upstream {}` block with one `server` line.
    static writeUpstream(filePath: string, upstreamName: string, port: string): IError | null {
        const content = `# Auto-generated by deployer on each activate — do not edit.
upstream ${upstreamName} {
    server 127.0.0.1:${port};
}
`;
        try {
            const tmp = filePath + ".tmp";
            try { fs.unlinkSync(tmp); } catch {}
            fs.writeFileSync(tmp, content, "utf-8");
            fs.renameSync(tmp, filePath);   // atomic on POSIX
            return null;
        } catch (e: any) {
            return { code: 48, message: "Failed to write nginx upstream file: " + String(e?.message ?? e), httpStatus: 500 };
        }
    }

    // Seeds the server-block config file from template — ONLY if the file doesn't already exist.
    // If the file is already there, this is a no-op (returns {seeded: false}) — deployer respects
    // whatever devops has done to it (certbot injections, custom locations, extra headers).
    static seedServerConfig(filePath: string, template: string, values: Record<string, string>): { seeded: boolean, error?: IError } {
        if (fs.existsSync(filePath)) {
            return { seeded: false };
        }
        try {
            let content = template;
            for (const [key, value] of Object.entries(values)) {
                content = content.replaceAll(`_{{${key}}}_`, value);
            }
            const leftover = content.match(/_\{\{[A-Za-z0-9_]+\}\}_/g);
            if (leftover && leftover.length > 0) {
                const unique = [...new Set(leftover)];
                logWarn("Unresolved placeholders in seeded nginx server config " + filePath + ": " + unique.join(", "));
            }
            const tmp = filePath + ".tmp";
            try { fs.unlinkSync(tmp); } catch {}
            fs.writeFileSync(tmp, content, "utf-8");
            fs.renameSync(tmp, filePath);
            return { seeded: true };
        } catch (e: any) {
            return { seeded: false, error: { code: 49, message: "Failed to seed nginx server config: " + String(e?.message ?? e), httpStatus: 500 } };
        }
    }

    // Reload hook — typically ["/usr/bin/sudo", "-n", "/bin/systemctl", "reload", "nginx"].
    // Non-fatal: config files are already committed on disk; a failed reload can be retried
    // manually. Hardened: async (doesn't block event loop), timeout 30s, absolute-path required,
    // minimal env (PATH only) so hook can't slurp our credentials, stderr captured for debugging.
    static async runHook(cmd: string[] | undefined | null): Promise<string | null> {
        if (!Array.isArray(cmd)) return null;
        const filtered = cmd.filter(s => typeof s === "string" && s.length > 0);
        if (filtered.length === 0) return null;

        if (!path.isAbsolute(filtered[0])) {
            const err = "nginx hook command must be an absolute path, got: " + filtered[0];
            logError(err);
            return err;
        }

        try {
            const result = await execFileAsync(filtered[0], filtered.slice(1), {
                timeout: 30_000,
                maxBuffer: 4 * 1024 * 1024,
                env: { PATH: process.env.PATH ?? "/usr/bin:/bin" },
            });
            if (result.stderr) logWarn("nginx hook stderr:", result.stderr);
            return null;
        } catch (e: any) {
            const err = String(e?.stderr || e?.message || e);
            logError("nginx hook failed:", err);
            return err;
        }
    }
}
